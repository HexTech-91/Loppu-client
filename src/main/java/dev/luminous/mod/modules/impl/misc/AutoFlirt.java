    @EventListener
    public void onUpdate(UpdateEvent event) {
        if (!this.timer.passedS(this.delay.getValue())) {
            return;
        }
        this.timer.reset();

        String target = this.targetPlayerName.getValue();
        if (target == null || target.trim().isEmpty()) {
            // 未设置目标玩家，不发送消息
            return;
        }

        // 获取随机消息
        String message = flirtMessages[random.nextInt(flirtMessages.length)];

        // 发送私聊消息给自定义目标
        mc.getNetworkHandler().sendChatCommand("tell " + target + " " + message);
    }
